#!/usr/bin/env bash
# Nova Bots helper for the Docker deployment in this folder.
#
#   ./nova-bots.sh start    build (if needed) and start the container
#   ./nova-bots.sh stop     stop the container
#   ./nova-bots.sh restart  restart the container
#   ./nova-bots.sh logs     follow the container logs (Ctrl+C to stop)
#   ./nova-bots.sh url      print the local URL and the login token
#   ./nova-bots.sh status   show container state and published port
#
# Host folders the Bots may work in (docker/.env):
#   ./nova-bots.sh mounts                 list the host folders and their container paths
#   ./nova-bots.sh mount <hostpath>       mount a host folder under /host
#   ./nova-bots.sh mount <hostpath> <containerpath>
#   ./nova-bots.sh unmount <hostpath>     remove one
#
# Public hostname (Cloudflare tunnel "bots"):
#   ./nova-bots.sh tunnel            print the public URLs
#   ./nova-bots.sh tunnel-status     connector state and reachability
#   ./nova-bots.sh tunnel-start      (re)start the connector
#   ./nova-bots.sh tunnel-stop       stop the connector
#   ./nova-bots.sh tunnel-logs       follow the connector log
#   cat token | ./nova-bots.sh tunnel-set-token   store the tunnel token and start
#
# The portal (sign-in API and the bridge to the engine) and the web front end:
#   ./nova-bots.sh portal-status    portal health, landing page and sign-in page
#   ./nova-bots.sh portal-logs      follow the portal log
#   ./nova-bots.sh web-logs        follow the web front end log
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$HERE/docker"

ENV_FILE=".env"
MOUNTS_FILE="compose.mounts.yml"
SERVICE="nova-bots"

# Read a key from .env. An empty or commented-out key yields the fallback.
env_get() {
  local key="$1" fallback="${2:-}"
  local value
  value="$(sed -n "s/^[[:space:]]*${key}=//p" "$ENV_FILE" 2>/dev/null | tail -1 | sed -e 's/[[:space:]]*#.*$//' -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/")"
  [ -n "$value" ] || value="$fallback"
  printf '%s' "$value"
}

env_set() {
  local key="$1" value="$2"
  if grep -qE "^[[:space:]]*${key}=" "$ENV_FILE" 2>/dev/null; then
    # Replace the value of an existing key, keeping any comment above it.
    local tmp
    tmp="$(mktemp)"
    awk -v k="$key" -v v="$value" '
      $0 ~ "^[[:space:]]*" k "=" { print k "=" v; next }
      { print }
    ' "$ENV_FILE" > "$tmp"
    mv "$tmp" "$ENV_FILE"
  else
    printf '%s=%s\n' "$key" "$value" >> "$ENV_FILE"
  fi
}

HOST_PORT="$(env_get NOVA_PORT 3080)"
HOST_SHARE="$(env_get HOST_SHARE '')"
# The Cloudflare connector for the public hostname (a user service, no root).
TUNNEL_DIR="${NOVA_TUNNEL_DIR:-$HOME/.nova/cloudflared}"
TUNNEL_TOKEN_FILE="${NOVA_TUNNEL_TOKEN:-$TUNNEL_DIR/token-bots}"

# Split BOT_MOUNTS into its entries, trimming spaces.
mount_list() {
  local raw="${1:-}"
  [ -n "$raw" ] || return 0
  local IFS=','
  for entry in $raw; do
    entry="$(printf '%s' "$entry" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
    [ -n "$entry" ] || continue
    printf '%s\n' "$entry"
  done
}

# The host part of an entry, without its container path.
mount_host() {
  printf '%s' "${1%%:*}"
}

# True when the host folder is already listed.
mount_listed() {
  local want="$1" entry
  while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    case "$entry" in
      "$want"|"$want":*) return 0 ;;
    esac
  done < <(mount_list "$2")
  return 1
}

# The mounts list: "hostpath" or "hostpath:containerpath", comma-separated.
# A bare host path lands under /host under its own name.
mount_entries() {
  local entry
  while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    case "$entry" in
      *:*) printf '%s\n' "$entry" ;;
      *) printf '%s:/host/%s\n' "$entry" "$(basename "$entry")" ;;
    esac
  done < <(mount_list "$(env_get BOT_MOUNTS '')")
}

# Write the compose override that carries the extra mounts. HOST_SHARE itself
# lives in compose.yml, so it needs no override.
write_mounts_file() {
  local entries tmp
  entries="$(mount_entries)"
  tmp="$(mktemp)"
  {
    echo "# Generated by nova-bots.sh from BOT_MOUNTS in .env. Do not edit by hand."
    echo "services:"
    echo "  $SERVICE:"
    if [ -n "$entries" ]; then
      echo "    volumes:"
      while IFS= read -r entry; do
        [ -n "$entry" ] || continue
        echo "      - \"$entry\""
      done <<< "$entries"
    fi
  } > "$tmp"
  mv "$tmp" "$MOUNTS_FILE"
}

# Compose with the override when there are extra mounts.
compose() {
  if [ -f "$MOUNTS_FILE" ] && grep -qE '^ +- ' "$MOUNTS_FILE" 2>/dev/null; then
    docker compose -f compose.yml -f "$MOUNTS_FILE" "$@"
  else
    docker compose -f compose.yml "$@"
  fi
}

case "${1:-start}" in
  start)
    write_mounts_file
    compose up -d
    echo
    "$HERE/nova-bots.sh" url
    ;;
  rebuild)
    # Build the image, start it, and refresh the plugin inside the profile.
    # A persisted profile keeps its own copy of the plugin, so without this
    # the running workspace would still serve the old interface.
    write_mounts_file
    compose up -d --build
    echo "→ refreshing the plugin in the profile"
    compose exec -T -u node \
      -e HOME=/home/node -e DSH_HOME=/data "$SERVICE" \
      sh -c 'dsh plugin --profile web remove nova-bots && dsh plugin --profile web add /opt/nova-bots/nova-bots.tgz' \
      >/dev/null
    compose restart "$SERVICE" >/dev/null
    echo "→ done"
    echo
    "$HERE/nova-bots.sh" url
    ;;
  stop)
    compose stop
    ;;
  restart)
    write_mounts_file
    compose up -d
    ;;
  logs)
    compose logs -f "$SERVICE"
    ;;
  url)
    # dsh prints the login URL (with the token) into the container log.
    LINE="$(compose logs "$SERVICE" 2>/dev/null | grep -Eo 'https?://[^ )]*token=[^ )]*' | tail -1 || true)"
    if [ -n "$LINE" ]; then
      LOCAL="$(printf '%s' "$LINE" | sed -E 's#https?://[^/]+#http://127.0.0.1:'"$HOST_PORT"'#')"
      echo "Login URL: $LOCAL"
      echo "After logging in, open: http://127.0.0.1:${HOST_PORT}/"
    else
      echo "Login URL: http://127.0.0.1:${HOST_PORT}/?token=... (see ./nova-bots.sh logs)"
    fi
    ;;
  status)
    compose ps
    echo
    systemctl --user --no-pager status nova-bots-portal 2>&1 | sed -n '1,6p'
    ;;
  tunnel)
    # The public hostname of the Nova Bots tunnel (the Cloudflare connector
    # runs as a user service; see nova-bots.sh tunnel-status).
    echo "https://bot.alilabsx.com/"
    echo "https://bots.alilabsx.com/"
    ;;
  portal-status)
    # The portal: the sign-in API and the bridge to the engine.
    systemctl --user --no-pager status nova-bots-portal 2>&1 | sed -n '1,8p'
    echo
    printf 'portal health   '
    curl -s -o /dev/null -w '%{http_code}\n' --max-time 10 http://127.0.0.1:13081/health || echo unreachable
    printf 'landing page    '
    curl -s -o /dev/null -w '%{http_code}\n' --max-time 10 http://127.0.0.1:${HOST_PORT}/ || echo unreachable
    printf 'sign-in page    '
    curl -s -o /dev/null -w '%{http_code}\n' --max-time 10 http://127.0.0.1:${HOST_PORT}/login || echo unreachable
    ;;
  portal-logs)
    journalctl --user -u nova-bots-portal -f -n 40
    ;;
  web-logs)
    compose logs -f nova-bots-web
    ;;
  tunnel-status)
    systemctl --user status cloudflared-bots --no-pager 2>&1 | sed -n '1,12p'
    echo
    for name in bot.alilabsx.com bots.alilabsx.com; do
      printf '%-22s ' "$name"
      curl -s -o /dev/null -w 'http %{http_code}\n' --max-time 15 "https://$name/" 2>/dev/null || echo "unreachable"
    done
    ;;
  tunnel-start)
    systemctl --user daemon-reload
    systemctl --user restart cloudflared-bots
    sleep 3
    systemctl --user --no-pager status cloudflared-bots 2>&1 | sed -n '1,8p'
    ;;
  tunnel-stop)
    systemctl --user stop cloudflared-bots
    ;;
  tunnel-logs)
    journalctl --user -u cloudflared-bots -f -n 40
    ;;
  tunnel-set-token)
    # Store the Cloudflare tunnel token (read from stdin) with tight
    # permissions, then (re)start the connector.
    umask 077
    cat > "$TUNNEL_TOKEN_FILE"
    chmod 600 "$TUNNEL_TOKEN_FILE"
    echo "token stored in $TUNNEL_TOKEN_FILE"
    "$HERE/nova-bots.sh" tunnel-start
    ;;
  mounts)
    echo "Host folders the Bots can reach:"
    if [ -n "$HOST_SHARE" ]; then
      echo "  $HOST_SHARE  ->  /host"
    fi
    mount_entries | while IFS= read -r entry; do
      [ -n "$entry" ] || continue
      echo "  ${entry%%:*}  ->  ${entry##*:}"
    done
    if [ -z "$HOST_SHARE" ] && [ -z "$(mount_entries)" ]; then
      echo "  (none — set HOST_SHARE or BOT_MOUNTS in docker/.env)"
    fi
    ;;
  mount)
    target="${2:-}"
    if [ -z "$target" ]; then
      echo "usage: $0 mount <hostpath> [containerpath]" >&2
      exit 1
    fi
    case "$target" in
      /*) ;;
      *) target="$(cd "$(dirname "$target")" 2>/dev/null && pwd)/$(basename "$target")" ;;
    esac
    if [ ! -d "$target" ]; then
      echo "$target is not a folder on this machine" >&2
      exit 1
    fi
    container_path="${3:-/host/$(basename "$target")}"
    current="$(env_get BOT_MOUNTS '')"
    entry="$target:$container_path"
    if [ -z "$current" ]; then
      current="$entry"
    elif ! mount_listed "$target" "$current"; then
      current="$current,$entry"
    fi
    env_set BOT_MOUNTS "$current"
    echo "Mounted $target at $container_path."
    echo "Run '$0 restart' to apply it."
    ;;
  unmount)
    target="${2:-}"
    if [ -z "$target" ]; then
      echo "usage: $0 unmount <hostpath>" >&2
      exit 1
    fi
    kept="$(mount_list "$(env_get BOT_MOUNTS '')" | while IFS= read -r entry; do
      [ -n "$entry" ] || continue
      case "$entry" in
        "$target"|"$target":*) continue ;;
      esac
      printf '%s\n' "$entry"
    done | paste -sd, -)"
    env_set BOT_MOUNTS "$kept"
    echo "Removed $target. Run '$0 restart' to apply it."
    ;;
  install-boot)
    # A user systemd unit, so the container comes back on every boot without
    # a login. Lingering keeps the user's services alive while logged out.
    UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
    UNIT="$UNIT_DIR/nova-bots.service"
    mkdir -p "$UNIT_DIR"
    cat > "$UNIT" <<EOF
[Unit]
Description=Nova Bots
After=network-online.target docker.service
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory=$HERE
ExecStart=$HERE/nova-bots.sh start
ExecStop=$HERE/nova-bots.sh stop
TimeoutStartSec=600
TimeoutStopSec=120

[Install]
WantedBy=default.target
EOF
    systemctl --user daemon-reload
    systemctl --user enable nova-bots.service
    # A user unit only runs at boot while the user is logged in, unless the
    # user lingers.
    if ! loginctl show-user "$(id -un)" -p Linger --value 2>/dev/null | grep -q yes; then
      loginctl enable-linger "$(id -un)" 2>/dev/null \
        && echo "Enabled lingering, so the unit starts at boot without a login." \
        || echo "Could not enable lingering. Log in once at boot, or run: sudo loginctl enable-linger $(id -un)"
    else
      echo "Lingering is on: the unit starts at boot without a login."
    fi
    systemctl --user restart nova-bots.service
    echo "Installed and started $UNIT"
    ;;
  uninstall-boot)
    systemctl --user disable --now nova-bots.service 2>/dev/null || true
    systemctl --user daemon-reload 2>/dev/null || true
    rm -f "${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/nova-bots.service"
    echo "Removed the boot unit. The container still returns with Docker (restart: unless-stopped)."
    ;;
  boot-status)
    echo "docker.service:      $(systemctl is-enabled docker 2>&1) / $(systemctl is-active docker 2>&1)"
    echo "linger for $(id -un):  $(loginctl show-user "$(id -un)" -p Linger --value 2>&1)"
    echo "nova-bots.service:      $(systemctl --user is-enabled nova-bots.service 2>&1) / $(systemctl --user is-active nova-bots.service 2>&1)"
    echo "container restart:   $(docker inspect "$(compose ps -q 2>/dev/null | head -1)" --format '{{.HostConfig.RestartPolicy.Name}}' 2>/dev/null || echo unknown)"
    ;;
  *)
    echo "usage: $0 {start|rebuild|stop|restart|logs|url|status|mounts|mount|unmount|install-boot|uninstall-boot|boot-status}" >&2
    exit 1
    ;;
esac
